/// The bytes IM reads for the signatures (`GetMagicPatternExtent`).
fn magic_extent() -> usize {
    MAGIC.iter().map(|(offset, signature, _, _)| offset + signature.len()).max().unwrap_or(0)
}

/// A registered format.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct FormatInfo {
    pub name: &'static str,
    pub module: &'static str,
    pub decoder: bool,
}

/// `GetMagickInfo` (names compare in any case).
fn format_info(name: &str) -> Option<(&'static str, &'static str, bool, bool, bool)> {
    FORMATS.iter().copied().find(|(known, ..)| known.eq_ignore_ascii_case(name))
}

/// `CompareMagic`.
fn signature_matches(head: &[u8], entry: &(usize, &[u8], &str, bool)) -> bool {
    let (offset, signature, _, skip_spaces) = *entry;
    let Some(mut rest) = head.get(offset..) else {
        return false;
    };
    if skip_spaces {
        while let Some((&byte, after)) = rest.split_first() {
            if !byte.is_ascii_whitespace() {
                break;
            }
            rest = after;
        }
    }
    rest.len() >= signature.len() && &rest[..signature.len()] == signature
}

/// `CompareMagickInfoExtent`.
fn compare_entries(a: &(usize, &[u8], &str, bool), b: &(usize, &[u8], &str, bool)) -> i64 {
    let mut delta = b.1.len() as i64 - a.1.len() as i64;
    if a.0 != b.0 {
        delta = a.0 as i64 - b.0 as i64;
        if a.0.max(b.0) <= 10 {
            delta = b.0 as i64 - a.0 as i64;
        }
    }
    delta
}

/// The signatures matched so far in the process (`magic_cache`), as
/// indices into [`MAGIC`], in the list's order.
static MAGIC_CACHE: Mutex<Vec<usize>> = Mutex::new(Vec::new());

/// `GetMagicInfo`: the cached signatures first, then the whole list; a
/// match found in the list joins the cache.
fn match_signature(head: &[u8]) -> Option<&'static str> {
    let mut cache = MAGIC_CACHE.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    if let Some(&index) = cache.iter().find(|&&index| signature_matches(head, &MAGIC[index])) {
        return Some(MAGIC[index].2);
    }
    let index = MAGIC.iter().position(|entry| signature_matches(head, entry))?;
    let position = cache.iter().position(|&cached| compare_entries(&MAGIC[index], &MAGIC[cached]) < 0).unwrap_or(cache.len());
    cache.insert(position, index);
    Some(MAGIC[index].2)
}

/// The format IM reads `path` as (`SetImageInfo` then `ReadImage`'s
/// lookup), or IM's error when it has no reader for it.
/// The formats registered as `ImplicitFormatType`: an extension naming one
/// leaves the format unset (`SetImageInfoFromExtension`), so only a
/// signature picks it. From the coders' `Register*Image`.
const IMPLICIT: [&str; 40] = [
    "CLIPBOARD", "CUBE", "GRADIENT", "RADIAL-GRADIENT", "HALD", "HISTOGRAM", "DATA", "INLINE", "LABEL", "MPR", "MPRI", "MSL",
    "MVG", "NULL", "POCKETMOD", "PLASMA", "FRACTAL", "R", "C", "G", "M", "B", "Y", "A", "O", "K", "SCREENSHOT", "SF3",
    "STEGANO", "GROUP4", "TILE", "TEXT", "HTTP", "HTTPS", "FTP", "FILE", "VID", "X", "XC", "CANVAS",
];

pub(crate) fn select(path: &Path) -> Result<FormatInfo> {
    let extension = path.extension().and_then(|value| value.to_str()).unwrap_or("").to_ascii_uppercase();
    let by_extension = if extension.is_empty() { None } else { format_info(&extension) };
    let implicit = by_extension.is_some() && IMPLICIT.contains(&extension.as_str());
    let mut magick = if implicit { String::new() } else { extension.clone() };
    let explicit = by_extension.is_some_and(|(_, _, _, explicit, _)| explicit);
    if !explicit {
        let mut head = vec![0u8; magic_extent()];
        let mut file = std::fs::File::open(path).with_context(|| format!("cannot open {}", path.display()))?;
        let mut count = 0;
        loop {
            let read = file.read(&mut head[count..])?;
            if read == 0 {
                break;
            }
            count += read;
            if count == head.len() {
                break;
            }
        }
        head.truncate(count);
        if let Some(name) = match_signature(&head) {
            // The extension's format, when it shares the signature's coder
            // (looked up even for an implicit format).
            let keep_extension = by_extension.is_some_and(|(_, module, _, _, use_extension)| use_extension && module.eq_ignore_ascii_case(name));
            magick = if keep_extension { extension.clone() } else { name.to_string() };
        }
    }
    match format_info(&magick) {
        Some((name, module, true, _, _)) => Ok(FormatInfo { name, module, decoder: true }),
        _ => bail!("NoDecodeDelegateForThisImageFormat `{magick}'"),
    }
}
